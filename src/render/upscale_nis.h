static const float LimitScale = (sharpen_slider >= 0.0) ? 1.25 : 1.0;
static const float kDetectRatio = 2.0 * 1127.0 / 1024.0;
static const float kDetectThres = 64.0 / 1024.0;
static const float kMinContrastRatio = 2.0;
static const float kMaxContrastRatio = 10.0;
static const float kSharpStartY = 0.45;
static const float kSharpEndY = 0.9;
static const float kSharpStrengthMin = max(0.0, 0.4 + sharpen_slider * MinScale * 1.2);
static const float kSharpStrengthMax = 1.6 + sharpen_slider * MaxScale * 1.8;
static const float kSharpLimitMin = max(0.1, 0.14 + sharpen_slider * LimitScale * 0.32);
static const float kSharpLimitMax = 0.5 + sharpen_slider * LimitScale * 0.6;
static const float kRatioNorm = 1.0 / (kMaxContrastRatio - kMinContrastRatio);
static const float kSharpScaleY = 1.0 / (kSharpEndY - kSharpStartY);
static const float kSharpStrengthScale = kSharpStrengthMax - kSharpStrengthMin;
static const float kSharpLimitScale = kSharpLimitMax - kSharpLimitMin;
